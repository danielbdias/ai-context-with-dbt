-- One-time account setup for the demo. Run as an admin with `task snowflake:setup`.
-- Passwords arrive as Snow CLI template variables (<% name %>), never in git.
-- Mirrors docs/grants-matrix.md: one least-privilege user per service, grants at
-- schema level, readers see MARTS only.
--
-- Snowflake limits what ClickHouse could pin per user. There is no readonly flag,
-- row cap or memory cap, so readers are read-only through grants alone and are
-- bounded by a statement timeout and a resource monitor.

USE ROLE ACCOUNTADMIN;

CREATE DATABASE IF NOT EXISTS AICTX;
-- RAW_STAGING holds dlt's merge staging tables (dlt names it <dataset>_staging).
CREATE SCHEMA IF NOT EXISTS AICTX.RAW;
CREATE SCHEMA IF NOT EXISTS AICTX.RAW_STAGING;
CREATE SCHEMA IF NOT EXISTS AICTX.STAGING;
CREATE SCHEMA IF NOT EXISTS AICTX.MARTS;

-- Cost guardrail: the demo should never burn more than this per month.
CREATE RESOURCE MONITOR IF NOT EXISTS AICTX_MONITOR
  WITH CREDIT_QUOTA = 10 FREQUENCY = MONTHLY START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 80 PERCENT DO NOTIFY ON 100 PERCENT DO SUSPEND;

CREATE WAREHOUSE IF NOT EXISTS AICTX_LOAD_WH
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  RESOURCE_MONITOR = AICTX_MONITOR;
CREATE WAREHOUSE IF NOT EXISTS AICTX_TRANSFORM_WH
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  RESOURCE_MONITOR = AICTX_MONITOR;
-- Shared by every reader. Each query is capped at 30 s, like the ClickHouse profile.
CREATE WAREHOUSE IF NOT EXISTS AICTX_READ_WH
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  STATEMENT_TIMEOUT_IN_SECONDS = 30 RESOURCE_MONITOR = AICTX_MONITOR;

CREATE ROLE IF NOT EXISTS AICTX_EL_LOADER;
CREATE ROLE IF NOT EXISTS AICTX_DBT_RUNNER;
CREATE ROLE IF NOT EXISTS AICTX_MCP_READER;
CREATE ROLE IF NOT EXISTS AICTX_CHARTS_READER;

-- LEGACY_SERVICE users may authenticate with a password and skip MFA.
CREATE USER IF NOT EXISTS EL_LOADER
  TYPE = LEGACY_SERVICE PASSWORD = '<% el_loader_password %>'
  DEFAULT_ROLE = AICTX_EL_LOADER DEFAULT_WAREHOUSE = AICTX_LOAD_WH;
CREATE USER IF NOT EXISTS DBT_RUNNER
  TYPE = LEGACY_SERVICE PASSWORD = '<% dbt_runner_password %>'
  DEFAULT_ROLE = AICTX_DBT_RUNNER DEFAULT_WAREHOUSE = AICTX_TRANSFORM_WH;
CREATE USER IF NOT EXISTS MCP_READER
  TYPE = LEGACY_SERVICE PASSWORD = '<% mcp_reader_password %>'
  DEFAULT_ROLE = AICTX_MCP_READER DEFAULT_WAREHOUSE = AICTX_READ_WH
  STATEMENT_TIMEOUT_IN_SECONDS = 30;
CREATE USER IF NOT EXISTS CHARTS_READER
  TYPE = LEGACY_SERVICE PASSWORD = '<% charts_reader_password %>'
  DEFAULT_ROLE = AICTX_CHARTS_READER DEFAULT_WAREHOUSE = AICTX_READ_WH
  STATEMENT_TIMEOUT_IN_SECONDS = 30;

GRANT ROLE AICTX_EL_LOADER TO USER EL_LOADER;
GRANT ROLE AICTX_DBT_RUNNER TO USER DBT_RUNNER;
GRANT ROLE AICTX_MCP_READER TO USER MCP_READER;
GRANT ROLE AICTX_CHARTS_READER TO USER CHARTS_READER;

GRANT USAGE ON WAREHOUSE AICTX_LOAD_WH TO ROLE AICTX_EL_LOADER;
GRANT USAGE ON WAREHOUSE AICTX_TRANSFORM_WH TO ROLE AICTX_DBT_RUNNER;
GRANT USAGE ON WAREHOUSE AICTX_READ_WH TO ROLE AICTX_MCP_READER;
GRANT USAGE ON WAREHOUSE AICTX_READ_WH TO ROLE AICTX_CHARTS_READER;

GRANT USAGE ON DATABASE AICTX TO ROLE AICTX_EL_LOADER;
GRANT USAGE ON DATABASE AICTX TO ROLE AICTX_DBT_RUNNER;
GRANT USAGE ON DATABASE AICTX TO ROLE AICTX_MCP_READER;
GRANT USAGE ON DATABASE AICTX TO ROLE AICTX_CHARTS_READER;

-- el_loader (dlt): owns RAW and RAW_STAGING, including merge staging tables and
-- schema evolution (ADD COLUMN). dlt keeps its state in RAW._DLT_* tables.
GRANT ALL PRIVILEGES ON SCHEMA AICTX.RAW TO ROLE AICTX_EL_LOADER;
GRANT ALL PRIVILEGES ON SCHEMA AICTX.RAW_STAGING TO ROLE AICTX_EL_LOADER;

-- dbt_runner: reads RAW, owns STAGING and MARTS. FUTURE grants matter because
-- tables dlt creates later must stay readable.
GRANT USAGE ON SCHEMA AICTX.RAW TO ROLE AICTX_DBT_RUNNER;
GRANT SELECT ON ALL TABLES IN SCHEMA AICTX.RAW TO ROLE AICTX_DBT_RUNNER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA AICTX.RAW TO ROLE AICTX_DBT_RUNNER;
GRANT ALL PRIVILEGES ON SCHEMA AICTX.STAGING TO ROLE AICTX_DBT_RUNNER;
GRANT ALL PRIVILEGES ON SCHEMA AICTX.MARTS TO ROLE AICTX_DBT_RUNNER;

-- Readers: MARTS only. dbt rebuilds tables with CREATE OR REPLACE, which drops
-- grants on the old object, so FUTURE grants are what keep readers working.
GRANT USAGE ON SCHEMA AICTX.MARTS TO ROLE AICTX_MCP_READER;
GRANT USAGE ON SCHEMA AICTX.MARTS TO ROLE AICTX_CHARTS_READER;
GRANT SELECT ON ALL TABLES IN SCHEMA AICTX.MARTS TO ROLE AICTX_MCP_READER;
GRANT SELECT ON ALL TABLES IN SCHEMA AICTX.MARTS TO ROLE AICTX_CHARTS_READER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA AICTX.MARTS TO ROLE AICTX_MCP_READER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA AICTX.MARTS TO ROLE AICTX_CHARTS_READER;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA AICTX.MARTS TO ROLE AICTX_MCP_READER;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA AICTX.MARTS TO ROLE AICTX_CHARTS_READER;
